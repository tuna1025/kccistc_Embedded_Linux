// LCD 저수준 제어 함수
void lcd_send_cmd(char cmd)
{
    char data_u, data_l;
    uint8_t data_t[4];
    data_u = (cmd & 0xf0);
    data_l = ((cmd << 4) & 0xf0);
    data_t[0] = data_u | 0x0C;
    data_t[1] = data_u | 0x08;
    data_t[2] = data_l | 0x0C;
    data_t[3] = data_l | 0x08;
    HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDR, (uint8_t *)data_t, 4, 100);
}

void lcd_send_data(char data)
{
    char data_u, data_l;
    uint8_t data_t[4];
    data_u = (data & 0xf0);
    data_l = ((data << 4) & 0xf0);
    data_t[0] = data_u | 0x0D;
    data_t[1] = data_u | 0x09;
    data_t[2] = data_l | 0x0D;
    data_t[3] = data_l | 0x09;
    HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDR, (uint8_t *)data_t, 4, 100);
}

void lcd_clear(void)
{
    lcd_send_cmd(0x01);
    HAL_Delay(2);
}

void lcd_put_cur(int row, int col)
{
    switch (row)
    {
        case 0: col |= 0x80; break;
        case 1: col |= 0xC0; break;
    }
    lcd_send_cmd(col);
}

void lcd_init(void)
{
    HAL_Delay(50);
    lcd_send_cmd(0x30);
    HAL_Delay(5);
    lcd_send_cmd(0x30);
    HAL_Delay(1);
    lcd_send_cmd(0x30);
    HAL_Delay(10);
    lcd_send_cmd(0x20);
    HAL_Delay(10);

    lcd_send_cmd(0x28);
    HAL_Delay(1);
    lcd_send_cmd(0x08);
    HAL_Delay(1);
    lcd_send_cmd(0x01);
    HAL_Delay(2);
    lcd_send_cmd(0x06);
    HAL_Delay(1);
    lcd_send_cmd(0x0C);
}

void lcd_send_string(char *str)
{
    while (*str) lcd_send_data(*str++);
}

// 1번: 닫힘 상태
void Locker_Lock(void)
{
    current_state = STATE_LOCKED;
    HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, GPIO_PIN_SET);

    lcd_clear();
    lcd_put_cur(0, 0);
    lcd_send_string("LOCKER #1       "); 
    lcd_put_cur(1, 0);
    lcd_send_string("STATUS: LOCKED  ");
}

// 2번: 원격 열림 상태
void Locker_Remote_Unlock(void)
{
    current_state = STATE_OPENED;
    HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, GPIO_PIN_RESET);

    lcd_clear();
    lcd_put_cur(0, 0);
    lcd_send_string("REMOTE UNLOCK   ");
    lcd_put_cur(1, 0);
    lcd_send_string("DOOR OPENED     ");
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        // 1. 단일 문자 명령 즉시 처리 (스마트폰 앱 테스트용: O/1=열림, L/0/C=닫힘)
        if (rx_data == 'O' || rx_data == 'o' || rx_data == '1')
        {
            Locker_Remote_Unlock();
        }
        else if (rx_data == 'L' || rx_data == 'l' || rx_data == 'C' || rx_data == 'c' || rx_data == '0')
        {
            Locker_Lock();
        }

        // 2. 개행 단위 문자열 명령 처리 (라즈베리파이 통신용: CMD_UNLOCK 등)
        if (rx_data == '\n' || rx_data == '\r')
        {
            if (rx_index > 0)
            {
                rx_buffer[rx_index] = '\0';

                if (strstr((char*)rx_buffer, "CMD_UNLOCK") != NULL)
                {
                    Locker_Remote_Unlock(); // LCD에 REMOTE UNLOCK 출력 및 도어 개방

                    // 응답 회신
                    char *ack = "[ACK_DOOR_OPENED]\n";
                    HAL_UART_Transmit(&huart1, (uint8_t*)ack, strlen(ack), 100);
                }
                else if (strstr((char*)rx_buffer, "CMD_LOCK") != NULL)
                {
                    Locker_Lock(); // LCD에 LOCKER #1: LOCKED 복귀

                    char *ack = "[ACK_DOOR_LOCKED]\n";
                    HAL_UART_Transmit(&huart1, (uint8_t*)ack, strlen(ack), 100);
                }
                rx_index = 0;
            }
        }
        else
        {
            if (rx_index < 63)
            {
                rx_buffer[rx_index++] = rx_data;
            }
        }

        // 다음 1바이트 수신 대기
        HAL_UART_Receive_IT(&huart1, &rx_data, 1);
    }
}
